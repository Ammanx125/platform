# app/web/routes/reports.py
"""
Standalone printable view of a structured report.

A structured report is created by the generate_structured_report action and
stored on a knowledge Document as doc_metadata["structured_report"]. This
route is the "screenshot it and send it to your boss" surface: one report,
no decision chrome, printable.

Access rules:
  - Tenant-scoped. Another tenant's document is a 404, not a 403, so the
    route never reveals that an id exists elsewhere.
  - Only documents generated by generate_structured_report are served.
  - A document WITH a generated_by marker but WITHOUT a structured_report
    key is not a report: 404.
  - A document whose stored report fails validation is a real defect (it
    was accepted for storage and is no longer renderable): surface it as a
    500 with an explanation rather than a blank page.
"""

from __future__ import annotations

import uuid
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import HTMLResponse
from pydantic import ValidationError
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models.knowledge import Document
from app.db.session import get_db
from app.schemas.report_structured import StructuredReport
from app.services.orchestration.report_builder import report_from_stored
from app.web.deps import HtmlUser, require_html_permission
from app.web.templating import base_context, templates

router = APIRouter()

REPORT_GENERATOR = "generate_structured_report"


@router.get(
    "/reports/{document_id}",
    response_class=HTMLResponse,
    dependencies=[Depends(require_html_permission("decision:run"))],
)
async def report_detail(
    document_id: uuid.UUID,
    request: Request,
    user: HtmlUser,
    db: Annotated[AsyncSession, Depends(get_db)],
):
    document = (
        await db.execute(
            select(Document).where(
                Document.id == document_id,
                Document.tenant_id == user.tenant_id,
            )
        )
    ).scalar_one_or_none()

    metadata = (document.doc_metadata or {}) if document is not None else {}
    if document is None or metadata.get("generated_by") != REPORT_GENERATOR:
        raise HTTPException(status_code=404, detail="report not found")

    raw_report = metadata.get("structured_report")
    if raw_report is None:
        raise HTTPException(status_code=404, detail="report not found")

    try:
        structured = StructuredReport.model_validate(raw_report)
    except ValidationError as exc:
        # The report was stored when it was valid and is not any more, so
        # something wrote bad data. Say which field, not just "error 500".
        first = exc.errors()[0]
        location = ".".join(str(part) for part in first.get("loc", ())) or "report"
        raise HTTPException(
            status_code=500,
            detail=(
                f"the stored report is malformed and cannot be rendered "
                f"({location}: {first.get('msg', 'invalid')})"
            ),
        ) from exc

    decision_run_id = metadata.get("decision_run_id")
    evidence: dict = {}
    if decision_run_id:
        from app.db.models.decision import DecisionRun

        try:
            run_id = uuid.UUID(str(decision_run_id))
        except (TypeError, ValueError):
            run_id = None
        if run_id is not None:
            run = (
                await db.execute(
                    select(DecisionRun).where(
                        DecisionRun.id == run_id,
                        DecisionRun.tenant_id == user.tenant_id,
                    )
                )
            ).scalar_one_or_none()
            if run is not None:
                evidence = run.evidence or {}

    report = report_from_stored(
        document.title,
        evidence,
        structured_report=structured,
    )

    return templates.TemplateResponse(
        request,
        "reports/report.html",
        {
            **base_context(),
            "loop_stage": "decision",
            "active_nav": "decisions",
            "tenant_name": str(user.tenant_id),
            "user_email": user.email,
            "document": document,
            "report": report,
        },
    )
