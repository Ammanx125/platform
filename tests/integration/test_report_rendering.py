# tests/integration/test_report_rendering.py
"""GET /reports/{document_id} — the standalone printable structured report."""

import uuid

import pytest
from httpx import AsyncClient

from app.db.models.knowledge import Document
from app.db.session import SessionLocal

VALID_REPORT = {
    "title": "Weekly Revenue Review",
    "sections": [
        {
            "section_type": "summary",
            "title": "Summary",
            "body": "Revenue grew for the third consecutive week.",
        },
        {
            "section_type": "kpis",
            "title": "Headline figures",
            "insights": [
                {
                    "observation": "Weekly ticket revenue reached 673,189.92 ETB.",
                    "business_impact": "Covers 118% of the weekly cost base.",
                    "recommendation": "Hold the current fare schedule.",
                    "evidence_ids": ["kpi:sales.total_revenue"],
                }
            ],
        },
        {
            "section_type": "attribution",
            "title": "What is driving it",
            "insights": [
                {
                    "observation": "Passenger volume on Route A rose 12%.",
                    "possible_causes": "Extra weekday services were added.",
                }
            ],
        },
    ],
}


def _csrf(client: AsyncClient) -> dict[str, str]:
    token = client.cookies.get("sansa_csrf")
    return {"X-CSRF-Token": token} if token else {}


async def _login(client: AsyncClient, email: str, password: str) -> None:
    await client.post("/api/v1/auth/login", json={"email": email, "password": password})


async def _create_document(
    tenant_id,
    *,
    title: str = "Weekly Revenue Review",
    metadata: dict | None = None,
) -> str:
    async with SessionLocal() as db:
        document = Document(
            tenant_id=tenant_id,
            source_id=None,
            title=title,
            content_type="markdown",
            raw_text="# Weekly Revenue Review",
            doc_metadata=(
                metadata
                if metadata is not None
                else {
                    "generated_by": "generate_structured_report",
                    "structured_report": VALID_REPORT,
                }
            ),
            status="ready",
        )
        db.add(document)
        await db.commit()
        await db.refresh(document)
        return str(document.id)


@pytest.mark.asyncio
async def test_report_renders_title_and_sections(client: AsyncClient, two_tenants: dict) -> None:
    await _login(client, two_tenants["email_a"], two_tenants["password"])
    document_id = await _create_document(two_tenants["tenant_a"])

    response = await client.get(f"/reports/{document_id}")

    assert response.status_code == 200, response.text
    html = response.text

    # Printable header
    assert "Weekly Revenue Review" in html
    assert "Generated by Sansa" in html
    assert "Print / save as PDF" in html
    assert "/static/css/report.css" in html

    # Every section, in order, with the shared renderer's markup
    assert html.count('class="report-section section-') == 3
    assert "section-summary" in html
    assert "section-kpis" in html
    assert "section-attribution" in html
    assert html.index("Summary") < html.index("Headline figures")

    # Insight fields
    assert "Revenue grew for the third consecutive week." in html
    assert "Covers 118% of the weekly cost base." in html
    assert "Hold the current fare schedule." in html
    assert "Extra weekday services were added." in html
    assert "kpi:sales.total_revenue" in html

    # No app chrome: the sidebar is not rendered on a printable report
    assert 'class="sidebar' not in html


@pytest.mark.asyncio
async def test_report_is_tenant_scoped(client: AsyncClient, two_tenants: dict) -> None:
    document_id = await _create_document(two_tenants["tenant_b"])
    await _login(client, two_tenants["email_a"], two_tenants["password"])

    response = await client.get(f"/reports/{document_id}")

    # 404, not 403: the route must not confirm the id exists elsewhere.
    assert response.status_code == 404


