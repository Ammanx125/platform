@pytest.mark.asyncio
async def test_malformed_report_returns_a_clear_error(
    client: AsyncClient, two_tenants: dict
) -> None:
    """A stored report that no longer validates must explain itself."""
    await _login(client, two_tenants["email_a"], two_tenants["password"])
    document_id = await _create_document(
        two_tenants["tenant_a"],
        metadata={
            "generated_by": "generate_structured_report",
            # Violates the discipline rule: attribution only, no
            # foundational section.
            "structured_report": {
                "title": "Broken",
                "sections": [{"section_type": "attribution", "title": "Causes"}],
            },
        },
    )

    response = await client.get(f"/reports/{document_id}")

    assert response.status_code == 500
    assert "malformed" in response.json()["detail"]
    assert "foundational" in response.json()["detail"]


